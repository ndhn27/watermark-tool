"""Tests for c2pa_provenance.py: dev-cert generation/reuse and the
sign_file()/read_manifest() round trip.

Skipped entirely if c2pa-python and/or cryptography aren't installed (both
are optional, --c2pa-only dependencies - see requirements.txt's comment)
rather than failing the whole suite over an opt-in feature nobody asked to
test right now.
"""

import pytest
from PIL import Image

import c2pa_provenance

pytestmark = pytest.mark.skipif(
    not c2pa_provenance.AVAILABLE,
    reason="c2pa-python and/or cryptography not installed (optional, --c2pa-only deps)",
)


def _solid_png(path, rgb=(120, 130, 140), size=(64, 64)):
    Image.new("RGB", size, rgb).save(path)
    return str(path)


def test_dev_cert_generates_then_reuses(tmp_path):
    cert_dir = tmp_path / "certs"
    cert_path1, key_path1, created1 = c2pa_provenance.get_or_create_dev_cert(cert_dir)
    assert created1 is True

    cert_bytes1 = open(cert_path1, "rb").read()
    key_bytes1 = open(key_path1, "rb").read()

    # Second call against the same directory must NOT regenerate - a fresh
    # cert every call would defeat the whole point of a stable signing
    # identity (see get_or_create_dev_cert's docstring).
    cert_path2, key_path2, created2 = c2pa_provenance.get_or_create_dev_cert(cert_dir)
    assert created2 is False
    assert cert_path2 == cert_path1
    assert open(cert_path2, "rb").read() == cert_bytes1
    assert open(key_path2, "rb").read() == key_bytes1


def test_sign_and_read_roundtrip_with_parent_and_author(tmp_path):
    original = _solid_png(tmp_path / "original.png", rgb=(200, 150, 100))
    watermarked = _solid_png(tmp_path / "watermarked.png", rgb=(190, 140, 90))

    # Generate an isolated dev cert under tmp_path rather than letting
    # sign_file() fall back to its default ~/.watermark-tool - keeps the
    # test hermetic (no writing to the real machine's home directory) while
    # still exercising the exact same dev-cert code path main() uses.
    cert_path, key_path, _ = c2pa_provenance.get_or_create_dev_cert(tmp_path / "certs")

    c2pa_provenance.sign_file(
        watermarked,
        title="my watermarked photo",
        author="Kiobh",
        parent_path=original,
        cert_path=cert_path,
        key_path=key_path,
    )

    info = c2pa_provenance.read_manifest(watermarked)
    assert info["has_manifest"] is True
    assert info["title"] == "my watermarked photo"
    assert info["author"] == "Kiobh"
    assert "original.png" in info["ingredients"]
    # c2pa.opened is auto-generated by the ingredient/EDIT intent; the
    # explicit action this module adds is the registered c2pa.watermarked id.
    assert "c2pa.opened" in info["actions"]
    assert c2pa_provenance.WATERMARK_ACTION in info["actions"]
    assert info["validation_state"] is not None

    # The dev cert is self-signed by design (see module docstring) - a
    # real reader is expected to flag it as untrusted, never as malformed.
    failures = info["validation_results"]["activeManifest"]["failure"]
    codes = [f["code"] for f in failures]
    assert "signingCredential.untrusted" in codes
    assert not any("malformed" in c.lower() for c in codes)


def test_sign_without_parent_uses_create_intent(tmp_path):
    solo = _solid_png(tmp_path / "solo.png")
    cert_path, key_path, _ = c2pa_provenance.get_or_create_dev_cert(tmp_path / "certs")
    c2pa_provenance.sign_file(solo, title="solo shot", cert_path=cert_path, key_path=key_path)

    info = c2pa_provenance.read_manifest(solo)
    assert info["has_manifest"] is True
    assert info["ingredients"] == []
    assert c2pa_provenance.WATERMARK_ACTION in info["actions"]
    # No parentOf ingredient means no auto c2pa.opened this time.
    assert "c2pa.opened" not in info["actions"]


def test_read_manifest_on_unsigned_file(tmp_path):
    plain = _solid_png(tmp_path / "plain.png")
    info = c2pa_provenance.read_manifest(plain)
    assert info == {"has_manifest": False}


def test_sign_file_requires_cert_and_key_together(tmp_path):
    target = _solid_png(tmp_path / "target.png")
    with pytest.raises(ValueError):
        c2pa_provenance.sign_file(target, cert_path="/some/cert.pem", key_path=None)


def test_unsupported_format_raises_not_swallowed(tmp_path):
    # .bmp is a format cli/watermark.py otherwise fully supports but that
    # c2pa-python's own supported-mime-types list does not (see
    # cli/c2pa_provenance.py's module docstring) - sign_file() must let
    # that error propagate rather than hiding it, so callers (watermark.py/
    # video.py) can decide to degrade to a printed note.
    import c2pa

    bmp_path = tmp_path / "shot.bmp"
    Image.new("RGB", (32, 32), (10, 20, 30)).save(bmp_path)
    cert_path, key_path, _ = c2pa_provenance.get_or_create_dev_cert(tmp_path / "certs")
    with pytest.raises(c2pa.C2paError):
        c2pa_provenance.sign_file(str(bmp_path), title="won't work", cert_path=cert_path, key_path=key_path)
    # And the original file must be left intact, not truncated by a failed
    # in-place replace (sign_file signs to a temp file first - see its
    # docstring on why).
    assert bmp_path.exists()
    assert Image.open(bmp_path).size == (32, 32)
